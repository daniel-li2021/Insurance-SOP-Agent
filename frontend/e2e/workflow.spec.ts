test('network recovery keeps the message and safely retries; panels remain bounded',async({page})=>{
  await page.goto('/')
  let originalId=''
  await page.route('**/api/turn',async route=>{originalId=route.request().postDataJSON().request_id;await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Language service unavailable. Retry safely.'})}); await page.unroute('**/api/turn')})
  await message(page,'My name is Margaret Chen.')
  await expect(page.getByRole('alert')).toContainText('Retry safely')
  await expect(page.getByRole('textbox')).toHaveValue('My name is Margaret Chen.')
  await expect(page.locator('.pending-message')).toContainText('personal details hidden')
  await expect(page.locator('.pending-message')).not.toContainText('Margaret')
  await page.route('**/api/turn',async route=>{expect(route.request().postDataJSON().request_id).toBe(originalId);await route.continue()})
  await page.getByRole('button',{name:'Retry',exact:true}).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.locator('.user-message')).toHaveCount(1)
  await expect(page.locator('.pending-message')).toHaveCount(0)
  // The server commits, but its response is lost: retry must reconcile, not append twice.
  await page.unroute('**/api/turn')
  let lostId=''
  await page.route('**/api/turn',async route=>{lostId=route.request().postDataJSON().request_id;await route.fetch();await route.abort();await page.unroute('**/api/turn')})
  await message(page,'What is the status?')
  await expect(page.getByRole('alert')).toBeVisible()
  await page.route('**/api/turn',async route=>{expect(route.request().postDataJSON().request_id).toBe(lostId);await route.continue()})
  await page.getByRole('button',{name:'Retry',exact:true}).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.locator('.user-message')).toHaveCount(2)
  expect(await page.evaluate(()=>document.documentElement.scrollHeight<=window.innerHeight)).toBeTruthy()
})

