test('authorization expiry hides protected content even if refresh fails',async({page})=>{
  await page.clock.install()
  await page.goto('/')
  await verified(page)
  await page.getByRole('button',{name:'Review summary',exact:true}).click()
  await expect(page.locator('.summary-preview')).toBeVisible()
  await page.route('**/api/session', route=>route.abort())
  await page.clock.fastForward(901_000)
  await expect(page.locator('.summary-preview')).toHaveCount(0)
  await expect(page.locator('.message-text')).not.toContainText('March 18, 2026')
  await expect(page.locator('.inspector-panel')).toContainText('Locked until verified')
})

test('expired session response removes protected content and supports a new session',async({page})=>{
  await page.goto('/')
  await verified(page)
  await page.route('**/api/turn',async route=>{
    await route.fulfill({status:401,contentType:'application/json',body:JSON.stringify({detail:'Session expired. Start a new session.'})})
    await page.unroute('**/api/turn')
  })
  await message(page, 'What is the payment?')
  await expect(page.getByRole('alert')).toContainText('Session expired')
  await expect(page.locator('.inspector-panel')).toContainText('Locked until verified')
  await expect(page.locator('.assistant-message')).not.toContainText('March 18, 2026')
  await page.getByRole('button',{name:'New session',exact:true}).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.locator('.user-message')).toHaveCount(0)
})

