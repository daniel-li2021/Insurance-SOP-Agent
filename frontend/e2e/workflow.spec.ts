test('BYOK errors clear keys; mobile dialog fits and restores focus',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Model settings',exact:true}).click()
  await page.getByLabel('Provider',{exact:true}).selectOption('gemini')
  await page.getByLabel('Credentials',{exact:true}).selectOption('byok')
  const key='browser-test-secret'
  await page.getByLabel('API key',{exact:true}).fill(key)
  await page.route('**/api/settings',async route=>{
    if(route.request().method()==='POST') {
      const body=route.request().postDataJSON()
      expect(body.api_key).toBe(key)
      expect(body.provider).toBe('gemini')
      await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'The provider rejected these credentials or model access.'})})
    } else await route.continue()
  })
  await page.getByRole('button',{name:'Validate & apply',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('rejected')
  await expect(page.getByLabel('API key',{exact:true})).toHaveValue('')
  expect(await page.evaluate(()=>JSON.stringify({local:localStorage,session:sessionStorage}))).not.toContain(key)
  await page.getByLabel('API key',{exact:true}).fill(key)
  await page.getByRole('button',{name:'Close model settings',exact:true}).click()
  await page.getByRole('button',{name:'Model settings',exact:true}).click()
  await expect(page.getByRole('dialog')).not.toContainText(key)
  await expect(page.locator('.model-label')).toContainText('Offline')
  await page.getByRole('button',{name:'Close model settings',exact:true}).click()
  await page.setViewportSize({width:390,height:844})
  const trigger=page.getByRole('button',{name:'Model settings',exact:true})
  await trigger.click()
  await page.getByLabel('Provider',{exact:true}).selectOption('anthropic')
  await page.getByLabel('Credentials',{exact:true}).selectOption('byok')
  await expect(page.getByLabel('API key',{exact:true})).toHaveAttribute('type','password')
  await page.screenshot({path:'../data/v2-model-settings-mobile.png',fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})
