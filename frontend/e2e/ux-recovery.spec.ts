test('missing-key status opens settings and expanded playground gains space on desktop and mobile', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('textbox', { name: 'Message ClaimFlow' })).toBeEnabled()
  await page.route('**/api/session', async route => {
    const response = await route.fetch()
    const session = await response.json()
    await route.fulfill({ response, json: { ...session, model: 'gpt-6.1-sol', model_connection: { ready: false, retain_for_new_sessions: false } } })
  })
  await page.reload()
  await expect(page.locator('.connection-notice')).toContainText('Missing key — no API call')
  const missingKey = page.getByRole('button', { name: 'Missing API key · Add key', exact: true })
  await expect(missingKey).toBeVisible()
  await expect(page.locator('.heading-actions')).not.toContainText('Live')
  await missingKey.click()
  await expect(page.getByRole('dialog', { name: 'Model settings', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close model settings', exact: true }).click()
  const input = page.getByRole('textbox', { name: 'Message ClaimFlow' })
  await input.fill('Keep this draft while expanding')
  for (const [name, width, height] of [['desktop', 1440, 1000], ['mobile', 390, 844]] as const) {
    await page.setViewportSize({ width, height })
    const rail = await page.getByRole('list', { name: 'Workflow progress' }).boundingBox()
    const chat = await page.getByRole('region', { name: 'Claim support conversation' }).boundingBox()
    expect(rail!.x + rail!.width).toBeLessThanOrEqual(chat!.x)
    await expect(page.getByRole('list', { name: 'Workflow progress' }).locator('li')).toHaveCount(4)
    const steps = await page.getByRole('list', { name: 'Workflow progress' }).locator('li').evaluateAll(nodes => nodes.map(el => el.getBoundingClientRect().top))
    expect(steps.every((top, n) => n === 0 || top > steps[n - 1])).toBe(true)
    expect(await input.evaluate(el => el.clientHeight)).toBeLessThan(45)
    const before = await page.locator('.conversation').evaluate(el => el.clientHeight)
    await page.getByRole('button', { name: 'Expand playground', exact: true }).click()
    await expect(page.getByRole('list', { name: 'Workflow progress' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Claims support', exact: true })).toHaveCount(0)
    const after = await page.locator('.conversation').evaluate(el => el.clientHeight)
    expect(after - before).toBeGreaterThan(25)
    await expect(input).toHaveValue('Keep this draft while expanding')
    await expect(missingKey).toBeInViewport({ ratio: 1 })
    await expect(page.getByRole('button', { name: 'New session', exact: true })).toBeVisible()
    await expect(input).toBeInViewport({ ratio: 1 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `../data/playground-space/expanded-${name}.png` })
    await page.getByRole('button', { name: 'Restore playground', exact: true }).click()
    await expect(page.getByRole('list', { name: 'Workflow progress' })).toBeVisible()
    expect(await page.locator('.conversation').evaluate(el => el.clientHeight)).toBe(before)
  }
  await page.unroute('**/api/session')
  await page.reload()
  await expect(missingKey).toHaveCount(0)
  await expect(page.locator('.model-label')).toContainText('Offline · Scripted')
  await expect(page.locator('.connection-notice')).toHaveCount(0)
})
